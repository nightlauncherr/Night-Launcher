#!/bin/sh
# Regenerates client/src/main/resources/assets/kestrel/tls/roots.pem from the
# system CA store: the current roots of the CAs Cloudflare uses (Let's Encrypt,
# Google Trust Services, SSL.com), plus DigiCert G2/G3 and Microsoft's 2017 roots
# (api.minecraftservices.com, used for player certificates). Java 8u51, which Minecraft
# 1.8.9 runs on, predates most of them.
set -eu
out=client/src/main/resources/assets/kestrel/tls/roots.pem
printf "# Public root CA certificates added to Java 8u51 trust for Night's own HTTPS\n# requests (cosmetics service, Mojang player certificates). Generated by tools/update_tls_roots.sh; not used\n# by Minecraft itself.\n" > "$out"
for f in ISRG_Root_X1 ISRG_Root_X2 GTS_Root_R1 GTS_Root_R3 GTS_Root_R4 DigiCert_Global_Root_G2 DigiCert_Global_Root_G3 \
         Microsoft_RSA_Root_Certificate_Authority_2017 Microsoft_ECC_Root_Certificate_Authority_2017 \
         SSL.com_Root_Certification_Authority_ECC SSL.com_Root_Certification_Authority_RSA \
         SSL.com_TLS_ECC_Root_CA_2022 SSL.com_TLS_RSA_Root_CA_2022; do
    echo "# $f" >> "$out"
    openssl x509 -in "/etc/ssl/certs/$f.pem" -outform PEM >> "$out"
done
