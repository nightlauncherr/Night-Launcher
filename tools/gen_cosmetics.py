    rgb = mix(rgb, c("ffe9a8"), moon * 1.0)
    st = np.mod(np.sin(px * 12.9898 + py * 78.233) * 43758.5453, 1) > 0.93
    return mix(rgb, c("ffffff"), st * 0.9)


